package io.mehow.laboratory

import io.mehow.laboratory.internal.InternalLaboratoryApi
import kotlin.reflect.KClass

/**
 * Factory that provides a set of known feature flags.
 *
 * Mainly used in QA tooling and debug inspection modules to expose available features. This should
 * not be needed in normal application logic.
 */
public interface FeatureFactory {
  /** Returns all known feature flag types. */
  public fun create(): Set<KClass<out Feature<*>>>

  /**
   * Returns the list of options for the given feature flag type, or `null` if this factory does not
   * know the feature.
   *
   * Code generated by the Laboratory Gradle plugin provides a concrete implementation that returns
   * each enum's declared entries. The default implementation returns `null` so that hand-written
   * [FeatureFactory] implementations keep compiling, in which case callers fall back to runtime
   * reflection on platforms that support it (JVM, Android).
   */
  @InternalLaboratoryApi
  public fun options(feature: KClass<out Feature<*>>): List<Feature<*>>? = null

  /**
   * Combines this factory with another. The resulting factory returns the union of both sets, and
   * option lookups try this factory first, falling back to the second one.
   */
  public operator fun plus(factory: FeatureFactory): FeatureFactory =
    object : FeatureFactory {
      override fun create() = this@FeatureFactory.create() + factory.create()

      @InternalLaboratoryApi
      override fun options(feature: KClass<out Feature<*>>): List<Feature<*>>? =
        this@FeatureFactory.options(feature) ?: factory.options(feature)
    }

  public companion object
}
